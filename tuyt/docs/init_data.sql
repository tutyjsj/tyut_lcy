-- 消息通知表（2026-05-29 新增：消息中心功能）
--   type: URGE(催办) / SUPERVISE(督办) / CALENDAR(工作日历) / DEADLINE(截止提醒) / SMS(短信)
--   read_status: 0未读 1已读
--   target_user_id: 接收消息的用户ID（对应 sys_user.id）
--   related_type: task / problem / sms / calendar
-- ============================================================
DROP TABLE IF EXISTS `message_notification`;
CREATE TABLE `message_notification` (
  `id` bigint NOT NULL,
  `type` varchar(20) NOT NULL COMMENT '消息类型:URGE/SUPERVISE/CALENDAR/DEADLINE/SMS',
  `title` varchar(200) NOT NULL COMMENT '消息标题',
  `content` text COMMENT '消息内容',
  `source_name` varchar(50) DEFAULT NULL COMMENT '来源人姓名',
  `source_id` bigint DEFAULT NULL COMMENT '来源人ID',
  `target_user_id` bigint NOT NULL COMMENT '接收用户ID',
  `related_id` bigint DEFAULT NULL COMMENT '关联业务ID',
  `related_type` varchar(20) DEFAULT NULL COMMENT '关联类型:task/problem/sms/calendar',
  `read_status` tinyint DEFAULT 0 COMMENT '0未读 1已读',
  `read_time` datetime DEFAULT NULL COMMENT '阅读时间',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` tinyint DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_target_user` (`target_user_id`),
  KEY `idx_type` (`type`),
  KEY `idx_read_status` (`read_status`),
  KEY `idx_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='消息通知表';

